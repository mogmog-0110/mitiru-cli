package build

import "testing"

// 生成済み CMakeLists から前回の engine 源を取り出せること。取り出しが壊れると
// 「engine 源が切り替わって全ビルドになる」警告が黙り、原因不明の長いビルドに戻る。
func TestEngineRootRe(t *testing.T) {
	prev := []byte(`# Generated by mitiru-cli.
set(MITIRU_ENGINE_ROOT "C:/Users/x/.mitiru/cache/engine-v0.31.0/MitiruEngine-0.31.0")
set(MITIRU_HEADER_ONLY ON)`)

	m := engineRootRe.FindSubmatch(prev)
	if m == nil {
		t.Fatal("engine root not found in generated CMakeLists")
	}
	got := string(m[1])
	want := "C:/Users/x/.mitiru/cache/engine-v0.31.0/MitiruEngine-0.31.0"
	if got != want {
		t.Fatalf("engine root = %q, want %q", got, want)
	}

	if engineRootRe.FindSubmatch([]byte("no root here")) != nil {
		t.Fatal("matched a file without an engine root")
	}
}
