//	<projectRoot>/build/cmake/      ← 生成された CMakeLists.txt の source tree
//	<projectRoot>/build/out/        ← cmake -B の output directory
func BuildDirs(projectRoot string) (cmakeSrcDir, cmakeOutDir string) {
	cmakeSrcDir = filepath.Join(projectRoot, "build", "cmake")
	cmakeOutDir = filepath.Join(projectRoot, "build", "out")
	return
}

// Configure は <projectRoot>/build/cmake/ に CMakeLists.txt を生成し、
// cmake に渡すべき source / output directory を返す。
// engineRootRe は生成済み CMakeLists から前回の engine 源を取り出す。
var engineRootRe = regexp.MustCompile(`set\(MITIRU_ENGINE_ROOT "([^"]+)"\)`)

func Configure(opts Options) (cmakeSrcDir, cmakeOutDir string, err error) {
	cmakeSrcDir, cmakeOutDir = BuildDirs(opts.ProjectRoot)
	if opts.OutDir != "" {
		cmakeOutDir = opts.OutDir // dist は別 out dir で dev build を汚さない
	}

	if err := os.MkdirAll(cmakeSrcDir, 0o755); err != nil {
		return "", "", fmt.Errorf("create build cmake dir: %w", err)
	}
	if err := os.MkdirAll(cmakeOutDir, 0o755); err != nil {
		return "", "", fmt.Errorf("create build out dir: %w", err)
	}

	mainCpp := filepath.Join(opts.ProjectRoot, "src", "main.cpp")
	if _, statErr := os.Stat(mainCpp); statErr != nil {
		return "", "", fmt.Errorf("expected source file %s: %w", mainCpp, statErr)
	}

	// host source は apps/ (現行 layout)、無ければ examples/ (旧 engine snapshot)。
	hostMain := resolveEngineSource(opts.EngineRoot, "mitiru_host", "main.cpp")
	if hostMain == "" {
		return "", "", fmt.Errorf(
			"engine reference host source missing: %s\n"+
				"  the cached engine tree looks incomplete or pre-v0.2.0;\n"+
				"  set MITIRU_ENGINE_ROOT to a v0.2.0+ checkout or re-run `mitiru build`\n"+
				"  with MITIRU_CACHE_DIR cleared",
			filepath.Join(opts.EngineRoot, "apps", "mitiru_host", "main.cpp"))
	}

	// 配布用ランチャ stub (任意)。古い engine では不在 → 空文字でテンプレートが skip。
	startMainAbs := ""
	if startMain := resolveEngineSource(opts.EngineRoot, "mitiru_start", "main.cpp"); startMain != "" {
		startMainAbs = toCMakePath(startMain)
	}

	// 単一 exe 化の器 (任意)。selfpack は console、selfrun は GUI subsystem。
	selfrunMainAbs, selfpackMainAbs := "", ""
	if p := resolveEngineSource(opts.EngineRoot, "mitiru_selfrun", "main.cpp"); p != "" {
		selfrunMainAbs = toCMakePath(p)
	}
	if p := resolveEngineSource(opts.EngineRoot, "mitiru_selfpack", "main.cpp"); p != "" {
		selfpackMainAbs = toCMakePath(p)
	}

	features, err := config.ResolveFeatures(opts.Features)
	if err != nil {
		return "", "", err
	}
	nav, err := resolveNavBake(opts)
	if err != nil {
		return "", "", err
	}
	lighting, err := resolveLightingBake(opts)
	if err != nil {
		return "", "", err
	}

	data := templateData{
		ProjectName:     opts.ProjectName,
		TargetName:      TargetName(opts.ProjectName),
		EngineRoot:      toCMakePath(opts.EngineRoot),
		ProjectRoot:     toCMakePath(opts.ProjectRoot),
		MainCppAbs:      toCMakePath(mainCpp),
		HostMainAbs:     toCMakePath(hostMain),
		StartMainAbs:    startMainAbs,
		SelfrunMainAbs:  selfrunMainAbs,
		SelfpackMainAbs: selfpackMainAbs,
		LegacyCEF:       engine.UsesLegacyCEF(opts.EngineRoot),
		UserWarnings:    engine.HeadersCleanAtW3(opts.EngineRoot),
		Features:        features,
		FeatureOptions:  config.FeatureOptions(features),
		Nav:             nav,
		Lighting:        lighting,
	}

	// engine 源の切り替わりは全ターゲットの作り直しになる。黙って始めると
	// 「毎回 400 近いコンパイルが走る」ようにしか見えないので、原因を先に言う。
	// 典型は、古いターミナルに残った MITIRU_ENGINE_ROOT が mitiru.toml のピンと
	// 交互に効いてしまうケース。
	if prev, readErr := os.ReadFile(filepath.Join(cmakeSrcDir, "CMakeLists.txt")); readErr == nil {
		if m := engineRootRe.FindSubmatch(prev); m != nil && string(m[1]) != data.EngineRoot {
			if opts.Stdout != nil {
				fmt.Fprintf(opts.Stdout,
					"エンジンの場所が %s から %s に変わったので、エンジン全体を作り直します。"+
						"心当たりがなければ、このターミナルに古い MITIRU_ENGINE_ROOT が残っていないか確かめてください"+
						" (この環境変数は mitiru.toml の指定より優先されます)。\n",
					string(m[1]), data.EngineRoot)
			}
		}
	}

	tmpl, err := template.New("CMakeLists").
		Option("missingkey=error").
		Parse(cmakeTemplate)
	if err != nil {
		return "", "", fmt.Errorf("parse cmake template: %w", err)
	}

	var rendered bytes.Buffer
	if err := tmpl.Execute(&rendered, data); err != nil {
		return "", "", fmt.Errorf("render cmake template: %w", err)
	}
	if err := writeFileIfChanged(filepath.Join(cmakeSrcDir, "CMakeLists.txt"), rendered.Bytes()); err != nil {
		return "", "", fmt.Errorf("write generated CMakeLists.txt: %w", err)
	}
	return cmakeSrcDir, cmakeOutDir, nil
}

// Artifacts は build pipeline が生み出すもの — user の DLL と、それを駆動する
// host exe の両方。`mitiru run` は `HostExePath DllPath` を呼び出す。
type Artifacts struct {
	// DeployDir は mitiru_host.exe と、<TargetName>.dll + assets/ を持つ
	// project ごとの subdirectory を含む directory。host は DLL を load する前に
	// ここを cwd にする想定。
	DeployDir string

	// HostExePath は mitiru_host.exe の absolute path。
	HostExePath string

	// DllPath は user の <TargetName>.dll の absolute path。
	DllPath string

	// DllRel は DllPath を DeployDir からの相対で表したもので、
	// `mitiru_host.exe <DllRel>` として mitiru_host に渡すのに適する。
	DllRel string
}

// Run は configure + build pipeline 全体を実行する。成功時に Artifacts を返す
// — host launcher と user の game DLL の両方。
func Run(opts Options) (*Artifacts, error) {
	if runtime.GOOS != "windows" {
		return nil, fmt.Errorf("mitiru build は今のところ Windows でだけ動きます (今の OS は %s です)。",
			runtime.GOOS)
	}

	if opts.Stdout == nil {
		opts.Stdout = os.Stdout
	}
	if opts.Stderr == nil {
		opts.Stderr = os.Stderr
	}
	if opts.Config == "" {
		opts.Config = "Debug"
	}

	vcvars, err := FindVcvars64()
	if err != nil {
		return nil, err
	}
	generator := opts.Generator
	if generator == "" {
		generator = generatorForVcvars(vcvars)
	}

	cmakeSrcDir, cmakeOutDir, err := Configure(opts)
	if err != nil {
		return nil, err
	}

	// 一度 configure 済みの build dir は CMakeCache.txt に generator を pin する。
	// generator を切り替える (例: NMake → Ninja) と cmake は
	// "generator mismatch" error で中断するので、cache 済み generator が
	// これから使うものと異なる場合は output tree を消す。生成された source
	// tree (cmakeSrcDir) は触らない — cmake -B の output のみ作り直す。
	if mismatch, cached := generatorMismatch(cmakeOutDir, generator); mismatch {
		console.Fverbosef(opts.Stdout,
			"Generator changed (%s -> %s); clearing %s for a clean reconfigure...\n",
			cached, generator, cmakeOutDir)
		if rmErr := os.RemoveAll(cmakeOutDir); rmErr != nil {
			return nil, fmt.Errorf("clear stale build dir %s: %w", cmakeOutDir, rmErr)
		}
		if mkErr := os.MkdirAll(cmakeOutDir, 0o755); mkErr != nil {
			return nil, fmt.Errorf("recreate build dir %s: %w", cmakeOutDir, mkErr)
		}
	}

	if err := engine.EnsureLegacyCEF(opts.EngineRoot, opts.Stdout); err != nil {
		return nil, err
	}

	timer := newPhaseTimer()
	if err := configureIfNeeded(vcvars, generator, cmakeSrcDir, cmakeOutDir, opts, timer); err != nil {
		return nil, err
	}
	if err := writeBuildMeta(cmakeOutDir, generator); err != nil {
		return nil, fmt.Errorf("write %s: %w", buildMetaFile, err)
	}

	console.Fverbosef(opts.Stdout, "Building %s (%s)...\n", opts.ProjectName, opts.Config)
	if err := runCMakeBuild(vcvars, cmakeOutDir, opts); err != nil {
		return nil, err
	}
	timer.mark("build")
	defer timer.report(opts.Stdout)

	targetName := TargetName(opts.ProjectName)

	// dry-run mode では実際には何も build されていない。caller が予定の
	// launch command を log できるよう placeholder の path を返す。
	if os.Getenv("MITIRU_DRY_RUN") == "1" {
		deploy := filepath.Join(cmakeOutDir, opts.Config)
		return &Artifacts{
			DeployDir:   deploy,
			HostExePath: filepath.Join(deploy, "mitiru_host.exe"),
			DllPath:     filepath.Join(deploy, targetName, targetName+".dll"),
			DllRel:      filepath.Join(targetName, targetName+".dll"),
		}, nil
	}

	// mitiru_host.exe を探す — その親 directory が deploy dir。
	hostCandidates := []string{
		filepath.Join(cmakeOutDir, opts.Config, "mitiru_host.exe"),
		filepath.Join(cmakeOutDir, "mitiru_host.exe"),
	}
	hostExe := ""
	for _, c := range hostCandidates {
		if _, err := os.Stat(c); err == nil {
			hostExe = c
			break
		}
	}
	if hostExe == "" {
		return nil, fmt.Errorf(
			"ビルドは通りましたが、%s の下に mitiru_host.exe が見つかりません。探した場所は %s です。",
			cmakeOutDir, strings.Join(hostCandidates, "、"))
	}

	deployDir := filepath.Dir(hostExe)
	dllPath := filepath.Join(deployDir, targetName, targetName+".dll")
	if _, err := os.Stat(dllPath); err != nil {
		return nil, fmt.Errorf(
			"ビルドは通りましたが、%s.dll が %s に見つかりません (%w)。",
			targetName, dllPath, err)
	}

	// assets/ を deploy 先へ常時同期する (R-04)。CMake 側の copy は DLL 再リンク
	// 時しか走らないため、RML/RCSS だけの編集もここで確実に反映させる。
	copied, syncErr := SyncAssets(
		filepath.Join(opts.ProjectRoot, "assets"),
		filepath.Join(deployDir, targetName, "assets"))
	if syncErr != nil {
		return nil, syncErr
	}
	if copied > 0 {
		console.Fverbosef(opts.Stdout, "Synced %d asset file(s) into %s\n",
			copied, filepath.Join(targetName, "assets"))
	}
	timer.mark("deploy")

	return &Artifacts{
		DeployDir:   deployDir,
		HostExePath: hostExe,
		DllPath:     dllPath,
		DllRel:      filepath.Join(targetName, targetName+".dll"),
	}, nil
}

// configureCommand は configure 段の cmake 呼び出し 1 行。
func configureCommand(generator, srcDir, outDir string, opts Options) string {
	// Multi-config generator (Visual Studio) は -A を受け付け、かつ必須。
	// single-config generator (NMake、Ninja) は -A を拒否し、明示的な
	// CMAKE_BUILD_TYPE を必要とする。
	var archAndType string
	if isMultiConfigGenerator(generator) {
		archAndType = "-A x64"
	} else {
		archAndType = "-DCMAKE_BUILD_TYPE=" + opts.Config
	}

	// dist 等が渡す追加 cache 変数 (例 MITIRU_HOST_GUI=ON)。
	var defs string
	for _, d := range opts.ExtraDefines {
		defs += " -D" + d
	}
	return fmt.Sprintf("cmake -S \"%s\" -B \"%s\" -G \"%s\" %s%s",
		srcDir, outDir, generator, archAndType, defs)
}

func runCMakeConfigure(vcvars, generator, srcDir, outDir string, opts Options) error {
	script := vcvarsPrelude(vcvars) + configureCommand(generator, srcDir, outDir, opts) + "\r\n"

	// CMake の configure 出力は成功時には純粋な diagnostic noise —
	// "Jolt not found"、"Tracy not found" のような feature detection 行は
	// 初回 user には error のように見え、first-touch の出力 budget を食い潰す。
	// これを capture し、configure が実際に失敗したときだけ表に出す。
	// -v / MITIRU_LOG=verbose で再度 opt-in できる (dry-run は既に独自の printer を通る)。
	if os.Getenv("MITIRU_DRY_RUN") == "1" || console.Verbose() {
		return runBatchScript("mitiru_configure", script, opts)
	}
	var buf bytes.Buffer
	quiet := opts
	quiet.Stdout = &buf
	quiet.Stderr = &buf
	if err := runBatchScript("mitiru_configure", script, quiet); err != nil {
		if buf.Len() > 0 {
			fmt.Fprint(opts.Stderr, buf.String())
		}
		return err
	}
	return nil
}

// vcvarsPrelude は cmake を駆動する全 batch script に必要な boilerplate を出す:
// VS Installer dir を PATH に載せ (vcvars64.bat が "is not recognized" noise を
// 出さずに vswhere.exe を見つけられるように)、その後 vcvars64.bat を有効化する。
//
// ninja は cl の /showIncludes の行を、configure で CMake が控えた接頭辞とバイト列で
// 比べて header 依存を拾う。日本語の cl はこの接頭辞を「メモ: インクルード ファイル:」と
// 出し、英語の言語パックが無ければ VSLANG=1033 でも変わらない。cl はコンソールの
// 出力コードページで書き、CMake は入力コードページで読むので、mitiru が出力だけを
// UTF-8 にした窓では接頭辞が化け、どの object も #deps 0 になる。chcp で入出力を
// 同じ UTF-8 にそろえ、configure と build で cl の出すバイト列を一致させる。
func vcvarsPrelude(vcvars string) string {
	return fmt.Sprintf(
		"@echo off\r\n"+
			"chcp 65001 >NUL\r\n"+
			"set \"PATH=C:\\Program Files (x86)\\Microsoft Visual Studio\\Installer;%%PATH%%\"\r\n"+
			"set \"VSLANG=1033\"\r\n"+
			"call \"%s\" >NUL\r\n"+
			"if errorlevel 1 exit /b %%errorlevel%%\r\n",
		vcvars)
}

func isMultiConfigGenerator(generator string) bool {
	return strings.HasPrefix(generator, "Visual Studio") ||
		generator == "Ninja Multi-Config" ||
		generator == "Xcode"
}

// generatorForVcvars は vcvars64.bat の path を、その toolchain 向けの
// CMake generator 名に対応づける。Windows では Ninja がどこでも default:
//   - NMake と同様、vcvars64.bat が設定する LIB / INCLUDE env var を直接消費する
//     ので、VS の multi-config generator がぶつかる MSBuild/SDK 解決問題
//     (古い Windows SDK しか入っていない machine での LNK1104 ucrtd.lib) を避ける。
//   - NMake と違い、CMakeFiles\<target>.dir\compiler_depend.make 内の
//     Windows path の drive-letter colon でつまずかない — NMake はそこで
//     "fatal error U1033: 構文エラー : 予期しない ':'" で中断するが、Ninja はしない。
//   - VS は ninja.exe を同梱し vcvars64.bat が PATH に載せるので、追加 install 不要。
//
// NMake や .sln を使いたい user は
// `mitiru build --generator "NMake Makefiles"` / `--generator "Visual Studio 17 2022"` で opt-in できる。
func generatorForVcvars(vcvars string) string {
	_ = vcvars
	return "Ninja"
}

// buildMetaFile は outDir 内に CLI が自分で書く状態メモのファイル名。cmake の
// 内部表現 (CMakeCache.txt のキー名や引用の形) は cmake のバージョンで変わりうるので、
// CLI 自身が要る値は CLI 自身の JSON に持つ (E11)。
const buildMetaFile = "mitiru_build.json"

type buildMeta struct {
	Generator string `json:"generator"`
}

func writeBuildMeta(outDir, generator string) error {
	data, err := json.MarshalIndent(buildMeta{Generator: generator}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, buildMetaFile), data, 0o644)
}

// generatorMismatch は outDir の mitiru_build.json に記録された generator を
// want と比較する。このファイルが無い build dir では CMakeCache.txt の
// CMAKE_GENERATOR:INTERNAL= 行を見る。どちらも読めなければ (false, "") を返し、
// 判断は cmake 自身に委ねる。
func generatorMismatch(outDir, want string) (bool, string) {
	if data, err := os.ReadFile(filepath.Join(outDir, buildMetaFile)); err == nil {
		var meta buildMeta
		if json.Unmarshal(data, &meta) == nil && meta.Generator != "" {
			return meta.Generator != want, meta.Generator
		}
	}

	f, err := os.Open(filepath.Join(outDir, "CMakeCache.txt"))
	if err != nil {
		return false, ""
	}
	defer f.Close()

	const prefix = "CMAKE_GENERATOR:INTERNAL="
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if strings.HasPrefix(line, prefix) {
			cached := strings.TrimSpace(strings.TrimPrefix(line, prefix))
			return cached != want, cached
		}
	}
	return false, ""
}

func runCMakeBuild(vcvars, outDir string, opts Options) error {
	script := vcvarsPrelude(vcvars) + cmakeBuildCommand(outDir, opts.Config, opts.Target) + "\r\n"

	// MITIRU_VERBOSE / dry-run は生ログをそのまま見たいときの opt-out。
	// 既定は /showIncludes の生ログ (header-only なエンジンで数十万行になる) を
	// 落とし、ninja の [N/M] 進捗だけ 1 行更新表示にする (E1)。
	if os.Getenv("MITIRU_DRY_RUN") == "1" || os.Getenv("MITIRU_VERBOSE") == "1" {
		return runBatchScript("mitiru_build", script, opts)
	}

	filtered := opts
	if console.Verbose() {
		pf := newBuildProgressFilter(opts.Stdout, TargetName(opts.ProjectName))
		filtered.Stdout = pf
		buildErr := runBatchScript("mitiru_build", script, filtered)
		if finishErr := pf.Finish(buildErr == nil); finishErr != nil && buildErr == nil {
			return finishErr
		}
		return buildErr
	}

	// 既定では進捗の 1 行だけを出し、診断行は失敗したときにまとめて出す。
	pf := newQuietBuildProgressFilter(opts.Stdout, TargetName(opts.ProjectName))
	var errBuf bytes.Buffer
	filtered.Stdout = pf
	filtered.Stderr = &errBuf
	buildErr := runBatchScript("mitiru_build", script, filtered)
	if finishErr := pf.Finish(buildErr == nil); finishErr != nil && buildErr == nil {
		return finishErr
	}
	if buildErr != nil && errBuf.Len() > 0 {
		fmt.Fprint(opts.Stderr, errBuf.String())
	}
	return buildErr
}

// cmakeBuildCommand は build 段の cmake 呼び出し 1 行。target が空なら全部を建てる。
func cmakeBuildCommand(outDir, config, target string) string {
	cmd := fmt.Sprintf("cmake --build \"%s\" --config %s", outDir, config)
	if target != "" {
		cmd += " --target " + target
	}
	return cmd
}

// runBatchScript は与えられた script を OS の temp dir 下に .bat として
// 書き出し、`cmd /c` 経由で実行する。(pipeline を cmd /c に inline で渡すのではなく)
// file に書くことで、path に space を含むときの Windows の command-line
// quoting bug を回避する。
func runBatchScript(prefix, script string, opts Options) error {
	if v := os.Getenv("MITIRU_DRY_RUN"); v == "1" {
		fmt.Fprintf(opts.Stdout, "[dry-run] would execute %s script:\n%s\n", prefix, script)
		return nil
	}

	tmp, err := os.CreateTemp("", prefix+"-*.bat")
	if err != nil {
		return fmt.Errorf("create temp batch: %w", err)
	}
	scriptPath := tmp.Name()
	defer func() { _ = os.Remove(scriptPath) }()

	if _, err := tmp.WriteString(script); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("write temp batch: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temp batch: %w", err)
	}

	cmd := exec.Command("cmd", "/c", scriptPath)
	cmd.Stdout = opts.Stdout
	cmd.Stderr = opts.Stderr
	cmd.Dir = opts.ProjectRoot
	if err := cmd.Run(); err != nil {
		return batchFailure(prefix, err)
	}
	return nil
}

// batchFailure は失敗したスクリプトの種類を利用者の言葉で言う。.bat の
// パスは実行後に消えるので、メッセージには入れない。
func batchFailure(prefix string, err error) error {
	switch prefix {
	case "mitiru_configure":
		return fmt.Errorf("cmake の構成に失敗しました (%w)。上の出力を確かめてください。", err)
	case "mitiru_build":
		return fmt.Errorf("ビルドに失敗しました (%w)。上のエラーを直してください。", err)
	}
	return fmt.Errorf("%s が失敗しました (%w)。", prefix, err)
}

// FindVcvars64 は `mitiru doctor` と同じ candidate set を使って vcvars64.bat を
// 探す。leaf package からの back-reference を避けるため、(internal/commands を
// import せず) ここに置いている。
func FindVcvars64() (string, error) {
	candidates := []string{
		`C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvars64.bat`,
		`C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars64.bat`,
		`C:\Program Files\Microsoft Visual Studio\2022\Professional\VC\Auxiliary\Build\vcvars64.bat`,
		`C:\Program Files\Microsoft Visual Studio\2022\Enterprise\VC\Auxiliary\Build\vcvars64.bat`,
		`C:\Program Files\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat`,
	}
	for _, p := range candidates {
		if _, err := os.Stat(p); err == nil {
			return p, nil
		}
	}
	matches, _ := filepath.Glob(
		`C:\Program Files\Microsoft Visual Studio\*\*\VC\Auxiliary\Build\vcvars64.bat`)
	if len(matches) > 0 {
		return matches[0], nil
	}
	return "", fmt.Errorf("vcvars64.bat が見つかりません。Visual Studio 2022 Build Tools (C++ のワークロード) を入れてから、mitiru doctor で確かめてください。")
}

// toCMakePath は Windows path を、CMake が常に受け付ける forward-slash 形式に
// 書き換える。生成 script 内での backslash-escape の頭痛も避けられる。
func toCMakePath(p string) string {
	return filepath.ToSlash(p)
}

// TargetName は user 向けの project 名を CMake-safe な target
// identifier に変換する。[A-Za-z0-9_] 以外を '_' に置き換える。
func TargetName(name string) string {
	out := make([]rune, 0, len(name))
	for _, r := range name {
		switch {
		case r >= 'A' && r <= 'Z',
			r >= 'a' && r <= 'z',
			r >= '0' && r <= '9',
			r == '_':
			out = append(out, r)
		default:
			out = append(out, '_')
		}
	}
	s := string(out)
	if s == "" || (s[0] >= '0' && s[0] <= '9') {
		s = "p_" + s
	}
	return s
}
