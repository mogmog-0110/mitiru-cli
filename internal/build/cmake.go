// Options は CMakeLists.txt 生成と cmake 呼び出しの両方を駆動する。
type Options struct {
	// ProjectRoot は mitiru.toml を含む directory の absolute path。
	ProjectRoot string

	// ProjectName は mitiru.toml の project.name。CMake の project() 名と
	// SHARED library target 名の両方に使われる。
	ProjectName string

	// EngineRoot は engine source の absolute path —
	// engine の top-level CMakeLists.txt を持つ directory。
	EngineRoot string

	// Config は "Debug" または "Release"。
	Config string

	// Generator は明示的な CMake generator の上書き (例: "NMake Makefiles"、
	// "Visual Studio 17 2022")。空なら検出した vcvars toolchain の default を使う。
	Generator string

	// ExtraDefines は configure に追加で渡す CMake cache 変数 ("NAME=VALUE" 形式)。
	// 例: dist が "MITIRU_HOST_GUI=ON" を渡す。
	ExtraDefines []string

	// OutDir は build 出力 dir の上書き (空なら build/out)。dist は dev build を
	// 汚さない別 dir を渡す (configure-time オプションの thrash 回避)。
	OutDir string

	// Target は `cmake --build` に渡す target (空なら全部)。standalone は自分の
	// exe だけを建てる。
	Target string

	// Features は mitiru.toml の [engine] features。名前は config.ResolveFeatures が引く。
	Features []string

	// NavSource は [nav] source (project root からの相対)。空ならナビメッシュを焼かない。
	NavSource string

	// NavArgs は [nav] args。mitiru_navbake にそのまま渡す。
	NavArgs []string

	// LightingSources は [lighting] source (project root からの相対、glob 可)。空なら光を焼かない。
	LightingSources []string

	// LightingArgs は [lighting] args。mitiru_lightbake にそのまま渡す。
	LightingArgs []string

	// Stdout は progress と cmake の出力を受け取る。
	Stdout io.Writer

	// Stderr は error 出力を受け取る。
	Stderr io.Writer
}

type templateData struct {
	ProjectName string
	TargetName  string
	EngineRoot  string
	ProjectRoot string
	MainCppAbs  string
	HostMainAbs string
	// 配布用 GUI ランチャ stub のソース (apps/mitiru_start/main.cpp、
	// 旧 engine では examples/mitiru_start/main.cpp)。
	// 無い古い engine では空文字 → テンプレートが target を生成しない。
	StartMainAbs string
	// 単一 exe 配布 (mitiru dist --onefile) の器。selfrun は配布物の頭に付く
	// 自己展開ランチャ、selfpack はそれに bundle を連結する梱包ツール。
	// StartMainAbs と同じく、無い engine では空文字で skip する。
	SelfrunMainAbs  string
	SelfpackMainAbs string
	// LegacyCEF は pin した engine が CEF 世代 (0.33 以前) のとき true。CEF の deploy と
	// HTML 用の JS の同梱はその世代だけに出す。
	LegacyCEF bool
	// UserWarnings は利用者の DLL を /W3 でコンパイルするか。エンジンのヘッダが /W3 で
	// 警告を出さない世代 (include/mitiru/core/Env.hpp がある) だけ立てる。古い engine の
	// ヘッダの警告で利用者の出力が埋まらないようにするため。
	UserWarnings bool
	// Features は [engine] features を引いたもの。DLL に link する target と、無いときの直し方。
	Features []config.EngineFeature
	// FeatureOptions は feature が要る engine の CMake option と、その値。
	FeatureOptions []config.FeatureOption
	// Nav は [nav] source があるときだけ非 nil。
	Nav *navBake
	// Lighting は [lighting] source があるときだけ非 nil。
	Lighting *lightingBake
}

// navBake はビルドの一工程でナビメッシュを焼くための値。
type navBake struct {
	SourceAbs string // レベルのメッシュ
	OutRel    string // 焼いた .navmesh の、DLL の隣からの相対
	OutDirRel string // OutRel の親 (make_directory 用)。DLL の隣そのものなら "."
	Args      string // mitiru_navbake への追加 option (CMake の引用済み、先頭に空白)
	ToolAbs   string // mitiru_navbake のソース。無い engine では空文字
}

